func TestOpenMPConfigPublicationModesAndLegacyOutput(t *testing.T) {
	for _, existing := range []bool{false, true} {
		for _, legacy := range []bool{false, true} {
			name := "new"
			if existing {
				name = "replacement"
			}
			if legacy {
				name += " with legacy"
			}
			t.Run(name, func(t *testing.T) {
				cfg := &run.Runtime{WorkingDir: t.TempDir(), RuntimeType: run.RuntimeTypeOpenMP}
				jsonPath := filepath.Join(cfg.WorkingDir, "config.json")
				legacyPath := filepath.Join(cfg.WorkingDir, "server.cfg")
				modes := map[string]os.FileMode{}
				if existing {
					for path, mode := range map[string]os.FileMode{jsonPath: 0o640, legacyPath: 0o600} {
						require.NoError(t, os.WriteFile(path, []byte("previous"), mode))
						info, err := os.Stat(path)
						require.NoError(t, err)
						modes[path] = info.Mode().Perm()
					}
				}
				if legacy {
					cfg.Extra = map[string]string{"price": "\u20ac", "alpha": "value"}
				}

				require.NoError(t, GenerateConfig(cfg))
				content, err := os.ReadFile(jsonPath)
				require.NoError(t, err)
				require.True(t, json.Valid(content))
				require.Equal(t, byte('\n'), content[len(content)-1])
				if legacy {
					content, err = os.ReadFile(legacyPath)
					require.NoError(t, err)
					require.Equal(t, "# server.cfg generated by sampctl for legacy plugin compatibility\nalpha value\nprice \x80\n", string(content))
				} else {
					require.NoFileExists(t, legacyPath)
				}
				for _, path := range []string{jsonPath, legacyPath} {
					if path == legacyPath && !legacy {
						continue
					}
					info, err := os.Stat(path)
					require.NoError(t, err)
					if existing {
						require.Equal(t, modes[path], info.Mode().Perm())
					} else if runtime.GOOS != "windows" {
						require.Equal(t, os.FileMode(0o600), info.Mode().Perm())
					}
				}
				staged, err := filepath.Glob(filepath.Join(cfg.WorkingDir, ".*"))
				require.NoError(t, err)
				require.Empty(t, staged)
			})
		}
	}
}

func TestOpenMPConfigPreparationErrorPrecedesUnsafeLegacyPath(t *testing.T) {
	cfg := &run.Runtime{WorkingDir: t.TempDir(), RuntimeType: run.RuntimeTypeOpenMP}
	nan := float32(math.NaN())
	cfg.StreamDistance = &nan
	configPath := filepath.Join(cfg.WorkingDir, "config.json")
	legacyPath := filepath.Join(cfg.WorkingDir, "server.cfg")
	require.NoError(t, os.WriteFile(configPath, []byte("previous"), 0o600))
	require.NoError(t, os.Mkdir(legacyPath, 0o700))
	require.NoError(t, os.WriteFile(filepath.Join(legacyPath, "keep"), nil, 0o600))

	err := GenerateConfig(cfg)
	require.ErrorContains(t, err, "failed to marshal structured config")
	var unsupported *json.UnsupportedValueError
	require.ErrorAs(t, err, &unsupported)
	content, readErr := os.ReadFile(configPath)
	require.NoError(t, readErr)
	require.Equal(t, "previous", string(content))
	require.FileExists(t, filepath.Join(legacyPath, "keep"))
}

func TestOpenMPConfigDoesNotCreateMissingWorkingDirectory(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "missing")
	err := GenerateConfig(&run.Runtime{WorkingDir: dir, RuntimeType: run.RuntimeTypeOpenMP})
	require.ErrorIs(t, err, os.ErrNotExist)
	require.NoDirExists(t, dir)
}

func TestOpenMPConfigReplacesHardlinkWithoutChangingOtherLink(t *testing.T) {
	cfg := &run.Runtime{WorkingDir: t.TempDir(), RuntimeType: run.RuntimeTypeOpenMP}
	target := filepath.Join(t.TempDir(), "untouched")
	require.NoError(t, os.WriteFile(target, []byte("external"), 0o600))
	if err := os.Link(target, filepath.Join(cfg.WorkingDir, "config.json")); err != nil {
		t.Skipf("hardlinks unavailable: %v", err)
	}

	require.NoError(t, GenerateConfig(cfg))
	content, err := os.ReadFile(target)
	require.NoError(t, err)
	require.Equal(t, "external", string(content))
	content, err = os.ReadFile(filepath.Join(cfg.WorkingDir, "config.json"))
	require.NoError(t, err)
	require.True(t, json.Valid(content))
}

func TestOpenMPConfigRefusesSymlinkDestinations(t *testing.T) {
	for _, filename := range []string{"config.json", "server.cfg"} {
		t.Run(filename, func(t *testing.T) {
			cfg := &run.Runtime{WorkingDir: t.TempDir(), RuntimeType: run.RuntimeTypeOpenMP, Extra: map[string]string{"legacy": "value"}}
			target := filepath.Join(t.TempDir(), "untouched")
			require.NoError(t, os.WriteFile(target, []byte("external"), 0o600))
			if err := os.Symlink(target, filepath.Join(cfg.WorkingDir, filename)); err != nil {
				t.Skipf("symlinks unavailable: %v", err)
			}

			err := GenerateConfig(cfg)
			content, readErr := os.ReadFile(target)
			require.NoError(t, readErr)
			require.Equal(t, "external", string(content))
			require.ErrorIs(t, err, os.ErrInvalid)
			info, statErr := os.Lstat(filepath.Join(cfg.WorkingDir, filename))
			require.NoError(t, statErr)
			require.NotZero(t, info.Mode()&os.ModeSymlink)
		})
	}
}
