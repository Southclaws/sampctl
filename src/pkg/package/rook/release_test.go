func TestUploadReleaseAsset(t *testing.T) {
	tmpDir := t.TempDir()
	archivePath := filepath.Join(tmpDir, "fixture.zip")
	require.NoError(t, os.WriteFile(archivePath, []byte("archive-data"), 0o644))

	var (
		gotMethod string
		gotPath   string
		gotName   string
		gotBody   []byte
	)

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotMethod = r.Method
		gotPath = r.URL.Path
		gotName = r.URL.Query().Get("name")
		var err error
		gotBody, err = io.ReadAll(r.Body)
		require.NoError(t, err)

		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write([]byte(`{"id":1,"name":"fixture.zip","state":"uploaded"}`))
	}))
	defer server.Close()

	client := github.NewClient(server.Client())
	baseURL, err := url.Parse(server.URL + "/")
	require.NoError(t, err)
	client.BaseURL = baseURL
	client.UploadURL = baseURL

	releaseID := int64(42)
	release := &github.RepositoryRelease{ID: &releaseID}
	pkg := pawnpackage.Package{}
	pkg.User = "owner"
	pkg.Repo = "repo"

	require.NoError(t, uploadReleaseAsset(releaseAssetUploadRequest{
		Context:     t.Context(),
		Client:      client,
		Package:     pkg,
		Release:     release,
		ArchivePath: archivePath,
	}))

	assert.Equal(t, http.MethodPost, gotMethod)
	assert.Equal(t, "/repos/owner/repo/releases/42/assets", gotPath)
	assert.Equal(t, "fixture.zip", gotName)
	assert.Equal(t, []byte("archive-data"), gotBody)
}

func TestCleanWorktreeCheck(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping integration test in short mode")
	}

	tmpDir := t.TempDir()

	repo, err := git.PlainInit(tmpDir, false)
	require.NoError(t, err)

	wt, err := repo.Worktree()
	require.NoError(t, err)

	status, err := wt.Status()
	require.NoError(t, err)
	assert.True(t, status.IsClean(), "Empty worktree should be clean")

	testFile := filepath.Join(tmpDir, "test.txt")
	err = os.WriteFile(testFile, []byte("content"), 0o644)
	require.NoError(t, err)

	_, err = wt.Add("test.txt")
	require.NoError(t, err)

	_, err = wt.Commit("test commit", &git.CommitOptions{
		Author: &object.Signature{
			Name:  "Test",
			Email: "test@test.com",
			When:  time.Now(),
		},
	})
	require.NoError(t, err)

	status, err = wt.Status()
	require.NoError(t, err)
	assert.True(t, status.IsClean(), "Worktree should be clean after commit")

	err = os.WriteFile(testFile, []byte("modified"), 0o644)
	require.NoError(t, err)

	status, err = wt.Status()
	require.NoError(t, err)
	assert.False(t, status.IsClean(), "Worktree should be dirty after modification")
}

